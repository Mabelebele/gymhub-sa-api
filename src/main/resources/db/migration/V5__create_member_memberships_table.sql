CREATE TABLE member_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    membership_plan_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    price_paid DECIMAL(10,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_member_memberships_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_member_memberships_plan FOREIGN KEY (membership_plan_id) REFERENCES membership_plans (id)
);

CREATE INDEX idx_member_memberships_member_status ON member_memberships (member_id, status);
