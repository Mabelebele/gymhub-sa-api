CREATE TABLE member_trainer_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    trainer_id BIGINT NOT NULL,
    assigned_date DATE NOT NULL,
    end_date DATE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_mta_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_mta_trainer FOREIGN KEY (trainer_id) REFERENCES trainers (id)
);

CREATE INDEX idx_mta_member_active ON member_trainer_assignments (member_id, active);
CREATE INDEX idx_mta_trainer_active ON member_trainer_assignments (trainer_id, active);

CREATE TABLE trainer_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainer_id BIGINT NOT NULL,
    day_of_week VARCHAR(10) NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_trainer_schedules_trainer FOREIGN KEY (trainer_id) REFERENCES trainers (id)
);

CREATE INDEX idx_trainer_schedules_trainer ON trainer_schedules (trainer_id);
