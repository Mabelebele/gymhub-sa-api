CREATE TABLE member_workout_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    workout_plan_id BIGINT NOT NULL,
    assigned_by_trainer_id BIGINT,
    assigned_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_mwp_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_mwp_plan FOREIGN KEY (workout_plan_id) REFERENCES workout_plans (id),
    CONSTRAINT fk_mwp_trainer FOREIGN KEY (assigned_by_trainer_id) REFERENCES trainers (id)
);

CREATE INDEX idx_mwp_member_status ON member_workout_plans (member_id, status);

CREATE TABLE workout_progress_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_workout_plan_id BIGINT NOT NULL,
    log_date DATE NOT NULL,
    duration_minutes INT,
    rating INT,
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_wpl_assignment FOREIGN KEY (member_workout_plan_id) REFERENCES member_workout_plans (id)
);

CREATE INDEX idx_wpl_assignment ON workout_progress_logs (member_workout_plan_id);
