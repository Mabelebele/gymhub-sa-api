CREATE TABLE member_diet_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    diet_plan_id BIGINT NOT NULL,
    assigned_by_trainer_id BIGINT,
    assigned_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_mdp_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_mdp_plan FOREIGN KEY (diet_plan_id) REFERENCES diet_plans (id),
    CONSTRAINT fk_mdp_trainer FOREIGN KEY (assigned_by_trainer_id) REFERENCES trainers (id)
);

CREATE INDEX idx_mdp_member_status ON member_diet_plans (member_id, status);

CREATE TABLE nutrition_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    goal_type VARCHAR(20) NOT NULL,
    start_weight_kg DECIMAL(5,2),
    target_weight_kg DECIMAL(5,2),
    target_date DATE,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_nutrition_goals_member FOREIGN KEY (member_id) REFERENCES members (id)
);

CREATE INDEX idx_nutrition_goals_member_status ON nutrition_goals (member_id, status);

CREATE TABLE weight_progress_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    log_date DATE NOT NULL,
    weight_kg DECIMAL(5,2) NOT NULL,
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_weight_logs_member FOREIGN KEY (member_id) REFERENCES members (id)
);

CREATE INDEX idx_weight_logs_member ON weight_progress_logs (member_id);
