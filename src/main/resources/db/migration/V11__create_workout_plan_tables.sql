CREATE TABLE workout_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(1000),
    difficulty_level VARCHAR(20),
    duration_weeks INT,
    created_by_trainer_id BIGINT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_workout_plans_trainer FOREIGN KEY (created_by_trainer_id) REFERENCES trainers (id)
);

CREATE TABLE workout_exercises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_plan_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    sets INT NOT NULL,
    reps INT NOT NULL,
    rest_seconds INT,
    sort_order INT NOT NULL,
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_workout_exercises_plan FOREIGN KEY (workout_plan_id) REFERENCES workout_plans (id)
);

CREATE INDEX idx_workout_exercises_plan ON workout_exercises (workout_plan_id);
