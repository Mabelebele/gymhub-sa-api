CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    member_membership_id BIGINT,
    amount DECIMAL(10,2) NOT NULL,
    method VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    receipt_number VARCHAR(50),
    gateway_reference VARCHAR(100),
    paid_at TIMESTAMP,
    notes VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_payments_receipt_number UNIQUE (receipt_number),
    CONSTRAINT fk_payments_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_payments_membership FOREIGN KEY (member_membership_id) REFERENCES member_memberships (id)
);

CREATE INDEX idx_payments_member ON payments (member_id);
CREATE INDEX idx_payments_gateway_reference ON payments (gateway_reference);
