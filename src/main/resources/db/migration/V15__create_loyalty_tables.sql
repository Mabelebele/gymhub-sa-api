CREATE TABLE loyalty_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    points_balance INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_loyalty_accounts_member UNIQUE (member_id),
    CONSTRAINT fk_loyalty_accounts_member FOREIGN KEY (member_id) REFERENCES members (id)
);

CREATE TABLE rewards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    points_cost INT NOT NULL,
    stock_quantity INT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE loyalty_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    type VARCHAR(20) NOT NULL,
    points INT NOT NULL,
    reason VARCHAR(255),
    balance_after INT NOT NULL,
    reward_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_loyalty_transactions_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_loyalty_transactions_reward FOREIGN KEY (reward_id) REFERENCES rewards (id)
);

CREATE INDEX idx_loyalty_transactions_member ON loyalty_transactions (member_id);
