CREATE TABLE diet_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(1000),
    daily_calorie_target INT,
    protein_grams INT,
    carbs_grams INT,
    fat_grams INT,
    created_by_trainer_id BIGINT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_diet_plans_trainer FOREIGN KEY (created_by_trainer_id) REFERENCES trainers (id)
);

CREATE TABLE diet_meals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diet_plan_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    calories INT,
    sort_order INT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_diet_meals_plan FOREIGN KEY (diet_plan_id) REFERENCES diet_plans (id)
);

CREATE INDEX idx_diet_meals_plan ON diet_meals (diet_plan_id);
